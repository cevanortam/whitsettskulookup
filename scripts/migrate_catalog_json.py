#!/usr/bin/env python3
"""Move the photos and handling notes in catalog.json into the new catalog.

    python3 scripts/migrate_catalog_json.py catalog.json migration/

Writes, inside the output folder:
  photos/<SKU>/1.<ext>   each photo decoded from base64
  migrate.sql            sets notes and photo keys (run after the pricing import)
  upload_photos.sh       uploads every photo to the R2 bucket

Text wrapped in ** ** in an old description (e.g. **MUST STAY IN STYROFOAM**)
becomes the SKU's notes. The description itself comes from the spreadsheet;
the old one is kept only for SKUs that aren't in it.
"""
import base64
import json
import os
import re
import sys

BUCKET = 'ceva-sku-photos'
EXTENSIONS = {'image/jpeg': 'jpg', 'image/png': 'png', 'image/webp': 'webp'}
NOTE_PATTERN = re.compile(r'\*\*(.+?)\*\*', re.S)


def sql_str(value):
    return "'" + value.replace("'", "''") + "'"


def split_notes(desc):
    notes = [n.strip() for n in NOTE_PATTERN.findall(desc)]
    rest = ' '.join(NOTE_PATTERN.sub(' ', desc).split())
    return rest, '\n'.join(notes)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out_dir = sys.argv[1], sys.argv[2]
    with open(src, encoding='utf-8') as f:
        catalog = json.load(f)

    os.makedirs(out_dir, exist_ok=True)
    sql, uploads = ['-- Generated by scripts/migrate_catalog_json.py'], ['#!/bin/sh', 'set -e', 'cd "$(dirname "$0")"']
    for key, item in sorted(catalog.items()):
        sku = re.sub(r'[^A-Z0-9]', '', key.upper())
        desc, notes = split_notes(item.get('desc') or '')
        photo_key = None

        data_url = item.get('imgBase64') or ''
        match = re.match(r'data:([\w/+-]+);base64,(.*)', data_url, re.S)
        if match and match.group(1) in EXTENSIONS:
            content_type = match.group(1)
            photo_key = f'{sku}/1.{EXTENSIONS[content_type]}'
            path = os.path.join(out_dir, 'photos', photo_key)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'wb') as img:
                img.write(base64.b64decode(match.group(2)))
            uploads.append(
                f'npx wrangler r2 object put {BUCKET}/{photo_key} '
                f'--file photos/{photo_key} --content-type {content_type} --remote'
            )

        sql.append(
            'INSERT INTO skus (sku, material, description, notes, photo_key, updated) VALUES '
            f"({sql_str(sku)}, {sql_str(sku)}, {sql_str(desc)}, {sql_str(notes)}, "
            f"{sql_str(photo_key) if photo_key else 'NULL'}, {sql_str(item.get('updated') or '')})\n"
            'ON CONFLICT(sku) DO UPDATE SET notes = excluded.notes, '
            'photo_key = COALESCE(excluded.photo_key, skus.photo_key);'
        )
        print(f"{sku}: {'photo' if photo_key else 'no photo'}{', notes: ' + notes if notes else ''}")

    with open(os.path.join(out_dir, 'migrate.sql'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(sql) + '\n')
    script = os.path.join(out_dir, 'upload_photos.sh')
    with open(script, 'w', encoding='utf-8') as f:
        f.write('\n'.join(uploads) + '\n')
    os.chmod(script, 0o755)


if __name__ == '__main__':
    main()
