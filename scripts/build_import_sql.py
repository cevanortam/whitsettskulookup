#!/usr/bin/env python3
"""Turn the SKU/pricing spreadsheet into SQL for the D1 catalog.

    python3 scripts/build_import_sql.py Pricing.xlsx import.sql
    cd worker && npx wrangler d1 execute ceva-sku-catalog --remote --file=../import.sql

Expects a sheet with the columns Material, Plnt, Unit Cost,
Material description and SKU. Re-running it with a newer spreadsheet updates
description, cost, material and plant, and leaves notes and photos alone.

The spreadsheet and the generated SQL contain pricing: keep them out of git.
"""
import re
import sys

import openpyxl

COLUMNS = {
    'sku': 'SKU',
    'material': 'Material',
    'description': 'Material description',
    'unit_cost': 'Unit Cost',
    'plant': 'Plnt',
}
ROWS_PER_STATEMENT = 200  # keeps each statement well under D1's 100 KB limit


def normalize_sku(value):
    return re.sub(r'[^A-Z0-9]', '', str(value or '').upper())


def text(value):
    return str(value).strip() if value is not None else ''


def sql_str(value):
    return "'" + value.replace("'", "''") + "'"


def sql_num(value):
    if value is None or value == '':
        return 'NULL'
    return repr(round(float(value), 2))


def read_rows(path):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    ws = wb.worksheets[0]
    rows = ws.iter_rows(values_only=True)
    header = [text(h) for h in next(rows)]
    missing = [name for name in COLUMNS.values() if name not in header]
    if missing:
        sys.exit(f'Missing column(s) in {path}: {", ".join(missing)}')
    index = {field: header.index(name) for field, name in COLUMNS.items()}

    for raw in rows:
        sku = normalize_sku(raw[index['sku']]) or normalize_sku(raw[index['material']])
        if not sku:
            continue
        yield {
            'sku': sku,
            'material': text(raw[index['material']]),
            'description': text(raw[index['description']]),
            'unit_cost': raw[index['unit_cost']],
            'plant': text(raw[index['plant']]),
        }


def dedupe(rows):
    """One row per SKU. A row with a description beats one without; otherwise the first wins."""
    best, dropped = {}, []
    for row in rows:
        kept = best.get(row['sku'])
        if kept is None:
            best[row['sku']] = row
        elif not kept['description'] and row['description']:
            dropped.append(kept)
            best[row['sku']] = row
        else:
            dropped.append(row)
    return list(best.values()), dropped


def write_sql(rows, out):
    out.write('-- Generated by scripts/build_import_sql.py\n')
    for start in range(0, len(rows), ROWS_PER_STATEMENT):
        chunk = rows[start:start + ROWS_PER_STATEMENT]
        values = ',\n'.join(
            f"({sql_str(r['sku'])}, {sql_str(r['material'])}, {sql_str(r['description'])}, "
            f"{sql_num(r['unit_cost'])}, {sql_str(r['plant'])}, date('now'))"
            for r in chunk
        )
        out.write(
            'INSERT INTO skus (sku, material, description, unit_cost, plant, updated) VALUES\n'
            f'{values}\n'
            'ON CONFLICT(sku) DO UPDATE SET\n'
            '  material = excluded.material,\n'
            "  description = CASE WHEN excluded.description <> '' THEN excluded.description ELSE skus.description END,\n"
            '  unit_cost = excluded.unit_cost,\n'
            '  plant = excluded.plant;\n'
        )


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dest = sys.argv[1], sys.argv[2]
    rows, dropped = dedupe(read_rows(src))
    with open(dest, 'w', encoding='utf-8') as out:
        write_sql(rows, out)

    no_desc = sum(1 for r in rows if not r['description'])
    print(f'{len(rows)} SKUs written to {dest}')
    print(f'{no_desc} have no description')
    for r in dropped:
        print(f"Skipped duplicate row for {r['sku']} (Material {r['material']}, cost {r['unit_cost']})")


if __name__ == '__main__':
    main()
